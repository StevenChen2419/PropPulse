const { test, expect } = require('@playwright/test');
const API = 'http://localhost:8000';

test('invented matchup: exact inactive Prop, team rest, opponent windows and preserved research', async ({ page, request }, testInfo) => {
  const manifest = await (await request.get(`${API}/__test__/manifest`)).json();
  const fixture = manifest.nba_matchup_demo;
  expect(fixture.synthetic).toBe(true);
  expect(fixture.real_response_obtained).toBe(false);
  const baseline = await (await request.get(`${API}/__test__/preservation`)).json();
  const forbidden = [];
  await page.route('**/*', route => {
    if (!['http://127.0.0.1:3199', API].includes(new URL(route.request().url()).origin)) {
      forbidden.push(route.request().url()); return route.abort();
    }
    return route.continue();
  });
  const url = `/player/${fixture.player_id}?prop_id=${fixture.prop_id}`;
  const research = await (await request.get(`${API}/players/${fixture.player_id}/research?prop_id=${fixture.prop_id}`)).json();
  expect(research.selected_prop.id).toBe(fixture.prop_id);
  expect(research.selected_prop.event_id).toBe(fixture.event_id);
  expect(research.selected_prop.actionable).toBe(false);
  const context = research.matchup_context;
  expect(context.status).toBe('available');
  expect(context.team_context.team_id).toBe('1610612738');
  expect(context.team_context.opponent_id).toBe('1610612753');
  expect(context.team_context.reference_date).toBe(fixture.reference_date);
  expect(context.team_context.last_recorded_game.date).toBe(fixture.last_game_date);
  expect(context.team_context.calendar_day_gap).toBe(1);
  expect(context.team_context.full_intervening_days).toBe(0);
  expect(context.team_context.conditional_back_to_back).toBe('yes');
  expect(context.opponent_history.recorded_appearances).toBe(12);
  expect(context.opponent_history.l5.appearances).toBe(5);
  expect(context.opponent_history.l10.appearances).toBe(10);
  expect(context.opponent_history.l5.points.valid_samples).toBe(4);
  expect(context.opponent_history.l5.points.average).toBe(4);
  expect(context.opponent_history.l5.minutes.valid_samples).toBe(4);
  expect(context.opponent_history.l5.assists.valid_samples).toBe(5);
  // Requested statistical scope must not hide independently supported team rest.
  const otherScope = await (await request.get(`${API}/players/${fixture.player_id}/research?prop_id=${fixture.prop_id}&competition=Playoffs`)).json();
  expect(otherScope.selected_prop.id).toBe(fixture.prop_id);
  expect(otherScope.matchup_context.team_context).toEqual(context.team_context);
  expect(otherScope.matchup_context.opponent_history.status).toBe('unavailable');
  expect(otherScope.matchup_context.opponent_history.l5.appearances).toBe(0);
  expect(otherScope.matchup_context.opponent_history.l5.points.average).toBeNull();
  expect(otherScope.season_summary.status).toBe('unavailable');
  await page.goto(url);
  const section = page.getByRole('region', { name: 'Matchup and team rest', exact: true });
  const season = page.getByRole('region', { name: 'Season statistics' });
  await expect(section).toBeVisible();
  await expect(section).toContainText('Matchup & Team Rest');
  await expect(section).toContainText('Orlando Magic');
  await expect(section).toContainText('Against This Opponent');
  await expect(section).toContainText('12');
  await expect(section).toContainText('4/5');
  await expect(season).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload();
  await expect(section).toContainText('Orlando Magic');
  await expect(page).toHaveURL(new RegExp(`prop_id=${fixture.prop_id}$`));
  await page.screenshot({ path: testInfo.outputPath('nba-matchup.png'), fullPage: true });
  await page.goto(`/player/${fixture.player_id}`);
  await expect(season).toBeVisible();
  await expect(section).toBeVisible();
  await expect(section).not.toContainText('Against This Opponent');
  const playerOnly = await (await request.get(`${API}/players/${fixture.player_id}/research`)).json();
  expect(playerOnly.matchup_context.status).toBe('unavailable');
  expect(playerOnly.matchup_context.team_context).toBeNull();
  expect(playerOnly.season_summary.status).toBe('available');
  await page.goto(`/player/${fixture.player_id}?prop_id=${fixture.unmapped_prop_id}`);
  await expect(season).toBeVisible();
  await expect(section).toBeVisible();
  await expect(section).not.toContainText('Against This Opponent');
  const unmapped = await (await request.get(`${API}/players/${fixture.player_id}/research?prop_id=${fixture.unmapped_prop_id}`)).json();
  expect(unmapped.selected_prop.id).toBe(fixture.unmapped_prop_id);
  expect(unmapped.matchup_context.status).toBe('unavailable');
  expect(unmapped.matchup_context.team_context).toBeNull();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto(url);
  await expect(section).toContainText('Against This Opponent');
  const after = await (await request.get(`${API}/__test__/preservation`)).json();
  expect(after.before).toEqual(baseline.before);
  expect(after.unchanged).toBe(true);
  expect(after.provider_http_attempts).toBe(0);
  expect(forbidden).toEqual([]);
});
